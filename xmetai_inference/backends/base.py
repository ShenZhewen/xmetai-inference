# -*- coding: utf-8 -*-
"""Shared runtime contract for inference backends: single-step forward; engines live in onnx.py / pt2.py."""
import logging
from abc import ABC, abstractmethod

import numpy as np
import torch

log = logging.getLogger(__name__)


def _fmt_dur(sec):
    """Seconds -> human-readable duration ('45s' / '12m34s' / '1h02m')."""
    sec = int(round(sec))
    if sec < 60:
        return f"{sec}s"
    if sec < 3600:
        return f"{sec // 60}m{sec % 60:02d}s"
    return f"{sec // 3600}h{(sec % 3600) // 60:02d}m"


def _default_gpu_mem_limit(device_id, fraction):
    """Query real GPU memory via torch and return the byte count available to the backend; None if unavailable."""
    try:
        import torch
    except ImportError:
        return None
    if not torch.cuda.is_available():
        return None
    try:
        props = torch.cuda.get_device_properties(device_id)
    except (AssertionError, RuntimeError):
        return None
    return max(int(props.total_memory * fraction), 0)


def _to_numpy(value):
    """torch -> numpy; used only at ONNX/earthkit/xarray/netCDF boundaries."""
    if isinstance(value, torch.Tensor):
        return value.detach().cpu().numpy()
    return np.asarray(value)


class BaseInferModel(ABC):
    """Common base class for all inference backends; subclasses implement load + forward.

    forward: x is (1, in_frames, C, H, W) and returns the full output in the same shape
    (the last frame is this step's forecast).
    """
    backend = "base"

    intra_op_threads = 0                 # 0 = backend decides (cli derives it from worker count)
    cudnn_algo_search = ""               # "" = default (EXHAUSTIVE)

    # Fallback non-negativity clamp before writing output; the real clamp happens in each
    # backend's output stage. If inverse normalization is misconfigured, this zeroes negative
    # normalized values, so the output looks plausible without raising an error.
    nonnegative_channels = ("tp",)

    # Model contract defaults; once materialized as real attributes, classes generated by
    # declare can be introspected directly (unit tests read them).
    history_steps = 2
    hour_interval = 6
    forecast_type = "deterministic"
    members = 1
    windowed_output = True
    valid_time_step_offset = 0

    @classmethod
    def declare(cls, class_name, *, model_name, channels, grid,
                output_channels=None, history_steps=None, hour_interval=None,
                forecast_type=None, members=None, windowed_output=None,
                gpu_state=None, valid_time_step_offset=None,
                time_features=None, **extra):
        """Generate a model class from parameters; only explicitly given attributes are set, the rest fall back to base/backend defaults.

        ``class_name`` also serves as ``__name__``. Models that need custom load / forward
        (FengQing, Pangu) are written as plain classes.
        """
        values = {
            "model_name": model_name,
            "input_channels": channels,
            "output_channels": output_channels or channels,
            "grid": grid,
            "history_steps": history_steps,
            "hour_interval": hour_interval,
            "forecast_type": forecast_type,
            "members": members,
            "windowed_output": windowed_output,
            "gpu_state": gpu_state,
            "valid_time_step_offset": valid_time_step_offset,
            "time_features": time_features,
        }
        attrs = {key: value for key, value in values.items() if value is not None}
        attrs.update(extra)
        attrs.setdefault(
            "__doc__",
            f"Declarative contract for model {model_name} ({cls.backend} backend).",
        )
        return type(class_name, (cls,), attrs)

    def __init__(self, device_id=0, gpu_mem_fraction=0.7):
        self.device_id = device_id
        self.gpu_mem_fraction = gpu_mem_fraction
        self.processing = None
        self.data_source = None

    def configure_processing(self, processing, data_source):
        """Bind the processing recipe from config."""
        self.processing = processing
        self.data_source = data_source
        return self

    def prepare_dataset_batch(self, batch, verbose=False):
        """DataLoader batch -> (inputs[B,T,C,H,W], init_times)."""
        if self.processing is None or self.data_source is None:
            raise RuntimeError("模型尚未绑定 processing 和 data_source")
        from xmetai_inference.utils.model_processors import build_dataset_batch

        return build_dataset_batch(batch, verbose=verbose)

    def release(self):
        """Common portion of backend resource cleanup; subclasses overriding this should call super()."""

    @abstractmethod
    def load(self, path):
        """Load the model onto self.device_id."""

    @abstractmethod
    def forward(self, x, step, valid_time):
        """Single forward step returning the full output window; the last frame is this step's forecast."""

    def describe(self):
        """Return a backend/device description (printed after load). Subclasses may override."""
        return self.backend

    def reset_runtime_state(self):
        """Clear cross-step internal state before each batch rollout (no-op by default)."""
        return None

    # When True and to_gpu / forward_gpu / to_numpy are implemented, state stays on GPU
    # throughout; GPU state does not support numpy recurrent transforms, so models that
    # need backfill should keep this False.
    gpu_state = False

    # Whether the graph's batch axis is symbolic; set by measurement at load time. When
    # False, Rollout falls back to one trajectory at a time.
    batch_axis_dynamic = False

    def to_gpu(self, x):
        """numpy initial state -> GPU carrier (implement when gpu_state=True)."""
        raise NotImplementedError

    def forward_gpu(self, state, step, valid_time):
        """GPU -> GPU single forward step returning the new state's GPU carrier (implement when gpu_state=True)."""
        raise NotImplementedError

    def to_numpy(self, state):
        """GPU carrier -> numpy (for writing output / extracting forecast frames; implement when gpu_state=True)."""
        raise NotImplementedError

    def to_dataset(self, step_state, save_names=None, lat=None, lon=None):
        """Output (C,H,W) for one step x one member -> xarray Dataset; save_names=None means all."""
        import xarray as xr

        channels = list(self.output_channels)
        if save_names is None:
            save_indices = list(range(len(channels)))
        else:
            name2idx = {str(c).lower(): i for i, c in enumerate(channels)}
            save_indices = [name2idx[str(n).lower()] for n in save_names]
        data_vars = {}
        for ci in save_indices:
            channel = channels[ci]
            arr = _to_numpy(step_state[ci])                # (H, W), north -> south
            if channel in self.nonnegative_channels:
                arr = np.maximum(arr, 0.0)
            data_vars[channel.upper()] = (("lat", "lon"), arr)
        return xr.Dataset(data_vars, coords={"lat": lat, "lon": lon})
